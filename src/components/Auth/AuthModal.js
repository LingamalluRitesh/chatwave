  root = root || (typeof window !== "undefined" ? window : (typeof global !== "undefined" ? global : {}));
  'use strict';

  class AuthModal {
    constructor() {}

    simpleHash(str) {
      let h = 0;
      for (let i = 0; i < str.length; i++) h = Math.imul(31, h) + str.charCodeAt(i) | 0;
      return Math.abs(h).toString(16).substring(0, 10);
    }
  }

  return new AuthModal();
